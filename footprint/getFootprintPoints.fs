                isAngle(definition.taWIDEST, ANGLE_360_BOUNDS);

                annotation { "Name" : "Taper Angle - INFLECTION", "UIHint" : UIHint.READ_ONLY, "Description" : 'Taper angle between ski center and line connecting inflection points' }
