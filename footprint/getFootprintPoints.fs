        {
            reportFeatureInfo(context, id, 'FOOTPRINT MUST BE CONTINUIOUS. NO FOOTPRINT DATA ANALYSIS. Cannot form a tangent path from selected edges');
        }

        if (!definition.retainCurves)
        {
            opDeleteBodies(context, id + "deleteCurves", {
                        "entities" : qCreatedBy(id + "fptWires", EntityType.BODY)
                    });
        }

    });

function genPointArray(context is Context, id is Id, targetCurve is Query, curveName is string, numPoints is number, includePoints is Query, refOrigin is Vector, reverseOrder is boolean, createSketch is boolean, sketchID is string)
{

    var lengthParams = range(0, 1, numPoints); // length increments along path to get points at.


    var edges = evaluateQuery(context, qOwnedByBody(targetCurve, EntityType.EDGE));

    addDebugEntities(context, qUnion(edges), DebugColor.CYAN);


    var edgePath = constructPath(context, qUnion(edges));


    var pathLines is array = evPathTangentLines(context, edgePath, lengthParams).tangentLines;
    var expPoints is array = [];
    for (var i = 0; i < size(pathLines); i += 1)
    {
        expPoints = append(expPoints, pathLines[i].origin - refOrigin);
    }

    //expPoints = sort(expPoints, function(a, b) {return (a[0] - b[0]);});
    if (reverseOrder)
    {
        expPoints = reverse(expPoints);
    }
    /*
       //println(curveName~' Points are:');
       for (var i = 0; i < size(expPoints); i += 1)
       {
       //println(expPoints[i][0].value*1000~', '~expPoints[i][1].value*1000);
       }
     */

    if (createSketch)
    {
        var fptSketch = newSketchOnPlane(context, id + ("sketch" ~ sketchID), {
                "sketchPlane" : plane(refOrigin, vector(0, 0, 1))
            });
        for (var i = 0; i < size(expPoints); i += 1)
        {
            skPoint(fptSketch, ("point" ~ i ~ sketchID), {
                        "position" : vector(expPoints[i][0], expPoints[i][1])
                    });
        }

        skSolve(fptSketch);

        /*
           setProperty(context, {
           "entities" : qOwnedByBody(fptSketch),
           "propertyType" : PropertyType.NAME,
           "value" : sketchID
           });
         */

    }

    return expPoints;
}


annotation { "Table Type Name" : "Footprint Points" }
export const fptPointTable = defineTable(function(context is Context, definition is map) returns TableArray
    precondition
    {
        // Define the parameters of the table type
    }
    {
        var columnDefinitions = [ //tableColumnDefinition("region", "Region"),
            tableColumnDefinition("x", "X - Value"),
            tableColumnDefinition("y", "Y - Value")
            //,tableColumnDefinition("z", "Z - Value")
        ];

        var tipRows = [];
        var rslRows = [];
        var tailRows = [];

        //1. Tip Points

        const tipPoints = getAttribute(context, {
                    "entity" : qOrigin(EntityType.BODY),
                    "name" : "tipEdgePoints"
                });

        var tableFormat = getAttributes(context, {
                    "entities" : qOrigin(EntityType.BODY),
                    "name" : "tableFormat"
                })[0];

        //println(tableFormat);

        var scaleFactor = 1;
        var suffixStr = '';
        if (tableFormat.tableUnits == exportUnits.MILLIMETER)
        {
            scaleFactor = 1000;
            suffixStr = ' mm';
        }

        if (tableFormat.tableUnits == exportUnits.INCH)
        {
            scaleFactor = 1000 / 25.4;
            suffixStr = ' in';
        }
        if (tableFormat.tableUnits == exportUnits.CENTIMETER)
        {
            scaleFactor = 100;
            suffixStr = ' cm';
        }

        //println('TABLE SCALEFACTOR = ' ~ scaleFactor);
        //println('TABLE SUFFIX STR = ' ~ suffixStr);


        for (var pt in tipPoints)
        {
            tipRows = append(tipRows, tableRow({ "x" : formatTableValue(context, pt[0], scaleFactor, tableFormat.sigFigs, suffixStr, tableFormat.cleanUnits), "y" : formatTableValue(context, pt[1], scaleFactor, tableFormat.sigFigs, suffixStr, tableFormat.cleanUnits) }));

        }

        //2. RSL Points
        const rslPoints = getAttribute(context, {
                    "entity" : qOrigin(EntityType.BODY),
                    "name" : "rslEdgePoints"
                });

        for (var pt in rslPoints)
        {
            rslRows = append(rslRows, tableRow({ "x" : formatTableValue(context, pt[0], scaleFactor, tableFormat.sigFigs, suffixStr, tableFormat.cleanUnits), "y" : formatTableValue(context, pt[1], scaleFactor, tableFormat.sigFigs, suffixStr, tableFormat.cleanUnits) }));
        }
        //3. Tail Points
        const tailPoints = getAttribute(context, {
                    "entity" : qOrigin(EntityType.BODY),
                    "name" : "tailEdgePoints"
                });

        for (var pt in tailPoints)
        {
            tailRows = append(tailRows, tableRow({ "x" : formatTableValue(context, pt[0], scaleFactor, tableFormat.sigFigs, suffixStr, tableFormat.cleanUnits), "y" : formatTableValue(context, pt[1], scaleFactor, tableFormat.sigFigs, suffixStr, tableFormat.cleanUnits) }));
        }


        // Compute the table



        return tableArray([table("TIP Points", columnDefinitions, tipRows), table("RSL Points", columnDefinitions, rslRows), table("TAIL points", columnDefinitions, tailRows)]);
    });

export function splitStr(splitStr is string, splitChar is string) returns array
{
    var retArray = [];
    var regexp = ".*" ~ splitChar ~ ".*";
    var stringArray = splitIntoCharacters(splitStr);
    var iterString is string = '';

    for (var i = 0; i < size(stringArray); i += 1)
    {
        if (!match(stringArray[i], regexp).hasMatch)
        {
            iterString = iterString ~ stringArray[i];

            if (i == size(stringArray) - 1)
            {
                retArray = append(retArray, iterString);
            }
        }
        else
        {
            retArray = append(retArray, iterString);
            iterString = '';
        }

    }

    return retArray;
}

export function formatTableValue(context is Context, val is ValueWithUnits, scaleFactor is number, sigFigs is number, suffixStr is string, cleanUnits is boolean)
{
    if (cleanUnits)
    {
        return roundToPrecision(val.value * scaleFactor, sigFigs);
    }
    else if (!cleanUnits)
    {
        return roundToPrecision(val.value * scaleFactor, sigFigs) ~ suffixStr;
    }
