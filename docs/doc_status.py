"""Documentation tracker: which explainers / decks exist, and what the user has done with them.

Manifest: docs/status.json. Report: docs/STATUS.md (regenerated by every command).

Each doc records three hashes so changes are detected, not remembered:
    written_hash   the doc as Claude last wrote it     -> differs now = the USER edited it
    state_hash     the doc when its state was last set -> differs after approval = re-review needed
    sources_hash   the documented .fs files when the doc was written -> differs = code moved on

States: planned -> draft -> reviewed -> approved. "approved" = MOVED TO ONSHAPE (user's definition, 2026-09-25):
a doc is approved only once it has been uploaded, which happens only when the user says so. Until then the user can
still find things to change, so "reviewed" is the highest state of anything not on Onshape.

usage (from the repo root):
    python docs/doc_status.py                     rescan, rewrite STATUS.md
    python docs/doc_status.py wrote <id>          Claude (re)wrote the doc: refresh written/sources hashes
    python docs/doc_status.py set <id> <state> ["note"]   record a user decision
    python docs/doc_status.py show <id>
    python docs/doc_status.py --dry-run           read-only: flags per doc + counts, writes nothing

Kinds: explainer (.md), deck (.pptx), sheet (1-2 page PDF; path = docs/sheets/<id>/<id>_sheet.pdf, html next to it).
Hashing normalizes CRLF -> LF (git core.autocrlf); old raw-byte hashes are still accepted until the next `wrote`/`set`.
"""
import hashlib
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs" / "status.json"
REPORT = ROOT / "docs" / "STATUS.md"
STATES = ["planned", "draft", "reviewed", "approved"]


def load():
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def save(m):
    MANIFEST.write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8")


def hash_files(paths, raw=False):
    """Hash of the existing files. Default normalizes CRLF -> LF so git core.autocrlf does not change it.
    raw=True is the legacy byte hash (hashes recorded before 2026-11-06 were raw); flags() accepts either."""
    h = hashlib.sha256()
    found = False
    for p in sorted(paths):
        f = ROOT / p
        if f.exists():
            found = True
            h.update(p.encode())
            data = f.read_bytes()
            if not raw and not p.lower().endswith((".pptx", ".pdf", ".png")):
                data = data.replace(b"\r\n", b"\n")
            h.update(data)
    return h.hexdigest()[:12] if found else None


def missing_sources(d):
    return [p for p in d.get("sources", []) if not (ROOT / p).exists()]


def same(d, paths, stored):
    """True if the stored hash matches the current files (normalized or legacy raw hash)."""
    return stored in (hash_files(paths), hash_files(paths, raw=True))


def doc_files(d):
    # The deck's reviewable content is the .pptx (the PDF is derived from it).
    return [d["path"]]


def flags(d):
    out = []
    cur = hash_files(doc_files(d))
    if cur is None:
        return ["missing"] if d["state"] != "planned" else []
    files = doc_files(d)
    if d.get("written_hash") and not same(d, files, d["written_hash"]):
        out.append("edited by user")
    if d["state"] == "approved" and d.get("state_hash") and not same(d, files, d["state_hash"]):
        out.append("changed since it went to Onshape")
    elif d["state"] == "reviewed" and d.get("state_hash") and not same(d, files, d["state_hash"]):
        out.append("changed since " + d["state"])
    if d.get("sources_hash") and not same(d, d.get("sources", []), d["sources_hash"]):
        out.append("code changed since written")
    ms = missing_sources(d)
    if ms:
        out.append("{} source path(s) missing".format(len(ms)))
    return out


def find(m, doc_id):
    for d in m["docs"]:
        if d["id"] == doc_id:
            return d
    sys.exit("no doc with id " + doc_id)


def report(m):
    lines = ["# Documentation status", "",
             "Generated by `python docs/doc_status.py` from `docs/status.json` -- do not edit by hand.", "",
             "States: planned -> draft -> reviewed -> approved (= moved to Onshape, only on the user's say-so).", ""]
    for kind, title in (("explainer", "Explainers (.md, repo only)"), ("deck", "Feature decks (.pptx -> .pdf for Onshape)"),
                        ("sheet", "Feature sheets (1-2 page .pdf, built from .html)")):
        lines += ["## " + title, "", "| id | title | state | flags | file | last change |", "|---|---|---|---|---|---|"]
        for d in m["docs"]:
            if d["kind"] != kind:
                continue
            last = d["history"][-1] if d.get("history") else {}
            f = ", ".join(flags(d)) or "-"
            lines.append("| {} | {} | **{}** | {} | `{}` | {} {} |".format(
                d["id"], d["title"], d["state"], f, d["path"], last.get("date", ""), last.get("note", "")))
        lines.append("")
    REPORT.write_text("\n".join(lines), encoding="utf-8")


def main(argv):
    m = load()
    today = date.today().isoformat()
    if len(argv) >= 2 and argv[0] == "wrote":
        d = find(m, argv[1])
        d["written_hash"] = hash_files(doc_files(d))
        d["sources_hash"] = hash_files(d.get("sources", []))
        if d["state"] == "planned":
            d["state"] = "draft"
        d.setdefault("history", []).append({"date": today, "state": d["state"], "note": "written by Claude"})
    elif len(argv) >= 3 and argv[0] == "set":
        d = find(m, argv[1])
        if argv[2] not in STATES:
            sys.exit("state must be one of " + ", ".join(STATES))
        d["state"] = argv[2]
        d["state_hash"] = hash_files(doc_files(d))
        d.setdefault("history", []).append({"date": today, "state": argv[2], "note": argv[3] if len(argv) > 3 else ""})
    elif len(argv) >= 2 and argv[0] == "show":
        d = find(m, argv[1])
        print(json.dumps(d, indent=2))
        print("flags:", flags(d))
        return
    elif argv and argv[0] == "--dry-run":
        # read-only: print flags per doc and counts; writes nothing (no status.json, no STATUS.md)
        counts = {}
        for d in m["docs"]:
            fl = flags(d)
            print("{:28} {:9} {:9} {}".format(d["id"], d["kind"], d["state"], ", ".join(fl) or "-"))
            for x in fl:
                key = x.split(" source path")[0] if "source path" in x else x
                key = "source path(s) missing" if "source path" in x else key
                counts[key] = counts.get(key, 0) + 1
        print("flag counts:", counts)
        return
    save(m)
    report(m)
    print(REPORT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main(sys.argv[1:])
